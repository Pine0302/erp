def main():
    os.makedirs(RAW, exist_ok=True)
    for t in TICKETS:
        t = dict(t)
        t.setdefault("extra_lines", [])
        t.setdefault("binding", "")
        t.setdefault("calculations", [])
        t.setdefault("total_amount", "")
        t.setdefault("uncertain", [])
        t.setdefault("notes", [])
        t.setdefault("stamps", [])
        for it in t["items"]:
            for k in ITEM_KEYS:
                it.setdefault(k, "")
        seq = os.path.splitext(os.path.basename(t["source_image"]))[0]
        path = os.path.join(RAW, seq + ".json")
        with open(path, "w", encoding="utf-8") as f:
            json.dump(t, f, ensure_ascii=False, indent=2)

    csv_path = os.path.join(BASE, "传票汇总.csv")
    header = ["序号", "传票号", "客户", "取货日期", "行号", "印刷品名", "印刷说明",
              "上版说明", "上版才数", "上版次数", "印法", "色别", "机印张数",
              "原材料名称", "规格",
              "数量", "金额", "装订", "金额合计", "手写计算", "其它手写行",
              "附注/印章", "存疑项"]
    with open(csv_path, "w", encoding="utf-8-sig", newline="") as f:
        w = csv.writer(f)
        w.writerow(header)
        for i, t in enumerate(TICKETS, 1):
            seq = os.path.splitext(os.path.basename(t["source_image"]))[0]
            rows = t["items"] or [{}]
            for j, it in enumerate(rows, 1):
                w.writerow([
                    i, t["ticket_no"], t["customer"], t["pickup_date"], j,
                    it.get("print_name", ""), it.get("print_note", ""),
                    it.get("plate_note", ""),
                    it.get("plates", ""), it.get("impressions", ""),
                    it.get("printing_method", ""), it.get("color", ""),
                    it.get("machine_sheets", ""), it.get("material", ""),
                    it.get("material_spec", ""), it.get("quantity", ""),
                    it.get("amount", ""), t.get("binding", ""),
                    t.get("total_amount", ""),
                    " | ".join(t.get("calculations", [])),
                    " | ".join(t.get("extra_lines", [])),
                    " | ".join(t.get("notes", []) + t.get("stamps", [])),
                    " | ".join(t.get("uncertain", [])),
                ])
    print("tickets: %d" % len(TICKETS))
    print("csv: %s" % csv_path)



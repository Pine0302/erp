def md_table(rows, header):
    out = ["| " + " | ".join(header) + " |", "| " + " | ".join(["---"] * len(header)) + " |"]
    for r in rows:
        out.append("| " + " | ".join(str(x).replace("\n", " ") if x else "—" for x in r) + " |")
    return "\n".join(out)


